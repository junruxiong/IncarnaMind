#!/usr/bin/env node
/**
 * UI audit: what the renderer loads, chunk by chunk, and what is inside the
 * initial chunk, grouped by package, from a build made with source maps:
 *
 *   npx electron-vite build --mode test --sourcemap --outDir <dir>
 *   node e2e/audit/bundle.mjs <dir> [out.json]
 *
 * Not part of the test suite.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { gzipSync } from "node:zlib";
import { SourceMapConsumer } from "source-map-js";

const outDir = process.argv[2];
if (!outDir) throw new Error("usage: node e2e/audit/bundle.mjs <build dir> [out.json]");

const kb = (bytes) => Math.round(bytes / 102.4) / 10;

function chunks(dir) {
  return readdirSync(dir)
    .filter((name) => /\.(m?js|css)$/.test(name))
    .map((name) => {
      const data = readFileSync(join(dir, name));
      return { name, kB: kb(data.length), gzipKB: kb(gzipSync(data).length) };
    })
    .sort((a, b) => b.kB - a.kB);
}

/** Which package (or src/ folder) a source path belongs to. */
function owner(source) {
  const path = source.replace(/^(\.\.\/)+/, "").replace(/^\/@fs/, "");
  const nm = path.lastIndexOf("node_modules/");
  if (nm >= 0) {
    const rest = path.slice(nm + "node_modules/".length).split("/");
    return rest[0]?.startsWith("@") ? `${rest[0]}/${rest[1]}` : (rest[0] ?? path);
  }
  const src = path.indexOf("src/");
  if (src >= 0) {
    const parts = path.slice(src).split("/");
    return parts.slice(0, Math.min(parts.length - 1, 4)).join("/");
  }
  return path;
}

/** Generated bytes per source package, by walking the source map's segments. */
function composition(jsPath) {
  const code = readFileSync(jsPath, "utf8");
  const map = JSON.parse(readFileSync(`${jsPath}.map`, "utf8"));
  const consumer = new SourceMapConsumer(map);
  const lines = code.split("\n");
  const segments = [];
  consumer.eachMapping((m) => {
    segments.push({ line: m.generatedLine, column: m.generatedColumn, source: m.source });
  });
  segments.sort((a, b) => a.line - b.line || a.column - b.column);
  const bytes = new Map();
  for (let i = 0; i < segments.length; i++) {
    const segment = segments[i];
    const next = segments[i + 1];
    const lineText = lines[segment.line - 1] ?? "";
    const end = next && next.line === segment.line ? next.column : lineText.length;
    const size = Buffer.byteLength(lineText.slice(segment.column, end));
    const key = segment.source ? owner(segment.source) : "(unmapped)";
    bytes.set(key, (bytes.get(key) ?? 0) + size);
  }
  return [...bytes.entries()]
    .map(([name, size]) => ({ name, kB: kb(size) }))
    .sort((a, b) => b.kB - a.kB);
}

const renderer = join(outDir, "renderer", "assets");
const html = readFileSync(join(outDir, "renderer", "index.html"), "utf8");
const initial = [...html.matchAll(/(?:src|href)="\.\/assets\/([^"]+)"/g)].map((m) => m[1]);
const entry = initial.find((name) => name.endsWith(".js"));

const report = {
  renderer: chunks(renderer),
  initial,
  main: chunks(join(outDir, "main")),
  preload: chunks(join(outDir, "preload")),
  fontsAndAssetsKB: kb(
    readdirSync(renderer)
      .filter((name) => !/\.(m?js|css|map)$/.test(name))
      .reduce((sum, name) => sum + statSync(join(renderer, name)).size, 0),
  ),
  entryComposition: entry ? composition(join(renderer, entry)).slice(0, 40) : [],
  lazyComposition: Object.fromEntries(
    readdirSync(renderer)
      .filter((name) => name.endsWith(".js") && name !== entry)
      .filter((name) => {
        try {
          return statSync(join(renderer, `${name}.map`)).isFile();
        } catch {
          return false;
        }
      })
      .map((name) => [name, composition(join(renderer, name)).slice(0, 10)]),
  ),
  mainComposition: Object.fromEntries(
    readdirSync(join(outDir, "main"))
      .filter((name) => name.endsWith(".js") && statSync(join(outDir, "main", name)).size > 500_000)
      .map((name) => [name, composition(join(outDir, "main", name)).slice(0, 15)]),
  ),
};

const out = process.argv[3];
if (out) writeFileSync(out, JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
